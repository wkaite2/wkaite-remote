#!/usr/bin/env python3
"""Apply the WKAite Remote build profile to pinned RustDesk source."""

from __future__ import annotations

import argparse
import base64
import binascii
import json
import re
from pathlib import Path
from typing import Any


class ProfileError(ValueError):
    """The build profile is incomplete or unsafe."""


class PatchError(RuntimeError):
    """The upstream source no longer matches a required patch anchor."""


HOST_RE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$")
PACKAGE_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_.]+$")
COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")

LIB_ANCHOR = "mod version;"
COMMON_ANCHOR = "pub fn load_custom_client() {"


def validate_profile(profile: dict[str, Any]) -> None:
    required = (
        "product_name",
        "package_id",
        "upstream_version",
        "upstream_commit",
        "server_host",
        "relay_host",
        "key",
    )
    missing = [name for name in required if not isinstance(profile.get(name), str) or not profile[name].strip()]
    if missing:
        raise ProfileError(f"missing profile fields: {', '.join(missing)}")
    if len(profile["product_name"].strip()) > 60:
        raise ProfileError("product_name must be 60 characters or fewer")
    if not PACKAGE_RE.fullmatch(profile["package_id"]):
        raise ProfileError("package_id is not a valid reverse-domain identifier")
    if not re.fullmatch(r"\d+\.\d+\.\d+", profile["upstream_version"]):
        raise ProfileError("upstream_version must use x.y.z format")
    if not COMMIT_RE.fullmatch(profile["upstream_commit"]):
        raise ProfileError("upstream_commit must be a lowercase 40-character SHA")
    for name in ("server_host", "relay_host"):
        host = profile[name]
        if "://" in host or "/" in host or ":" in host or not HOST_RE.fullmatch(host):
            raise ProfileError(f"{name} must be a hostname or IPv4 address without a port")
    try:
        decoded_key = base64.b64decode(profile["key"], validate=True)
    except (binascii.Error, ValueError) as exc:
        raise ProfileError("key must be valid base64") from exc
    if len(decoded_key) != 32:
        raise ProfileError("key must decode to 32 bytes")


def rust_string(value: str) -> str:
    # JSON string escaping is compatible with Rust for this ASCII-only profile.
    return json.dumps(value, ensure_ascii=True)


def render_profile(profile: dict[str, Any]) -> str:
    return f'''// Generated by client-builder/scripts/configure_source.py. Do not edit.
use base::config::keys;
use hbb_common::config;

pub const PRODUCT_NAME: &str = {rust_string(profile["product_name"])};
pub const PACKAGE_ID: &str = {rust_string(profile["package_id"])};
pub const UPSTREAM_VERSION: &str = {rust_string(profile["upstream_version"])};
pub const SERVER_HOST: &str = {rust_string(profile["server_host"])};
pub const RELAY_HOST: &str = {rust_string(profile["relay_host"])};
pub const KEY: &str = {rust_string(profile["key"])};

pub fn apply() {{
    *config::APP_NAME.write().unwrap() = PRODUCT_NAME.to_owned();
    *config::PROD_RENDEZVOUS_SERVER.write().unwrap() = SERVER_HOST.to_owned();

    {{
        let mut options = config::OVERWRITE_SETTINGS.write().unwrap();
        options.insert(keys::OPTION_CUSTOM_RENDEZVOUS_SERVER.into(), SERVER_HOST.into());
        options.insert(keys::OPTION_RELAY_SERVER.into(), RELAY_HOST.into());
        options.insert(keys::OPTION_KEY.into(), KEY.into());
        options.insert(keys::OPTION_ENABLE_CHECK_UPDATE.into(), "N".into());
        options.insert(keys::OPTION_ALLOW_AUTO_UPDATE.into(), "N".into());
    }}

    {{
        let mut builtin = config::BUILTIN_SETTINGS.write().unwrap();
        builtin.insert(keys::OPTION_REGISTER_DEVICE.into(), "N".into());
        builtin.insert(keys::OPTION_HIDE_SERVER_SETTINGS.into(), "Y".into());
    }}
}}
'''


def inject_once(text: str, anchor: str, addition: str, anchor_after: str) -> str:
    if addition in text:
        return text
    if anchor not in text:
        raise PatchError(f"required upstream anchor not found: {anchor!r}")
    return text.replace(anchor, anchor_after, 1)


def replace_strict(text: str, old: str, new: str, path: Path) -> str:
    if new in text:
        return text
    if old not in text:
        raise PatchError(f"branding anchor not found in {path}: {old!r}")
    return text.replace(old, new, 1)


def configure_source(profile: dict[str, Any], root: Path) -> None:
    validate_profile(profile)
    lib_path = root / "src" / "lib.rs"
    common_path = root / "src" / "common.rs"
    for path in (lib_path, common_path):
        if not path.is_file():
            raise PatchError(f"required upstream file not found: {path}")

    lib = lib_path.read_text(encoding="utf-8")
    common = common_path.read_text(encoding="utf-8")

    branding_updates: list[tuple[Path, str, str]] = []
    replacements = (
        (
            "flutter/android/app/src/main/AndroidManifest.xml",
            'android:label="RustDesk"',
            f'android:label="{profile["product_name"]}"',
        ),
        (
            "flutter/android/app/build.gradle",
            'applicationId "com.carriez.flutter_hbb"',
            f'applicationId "{profile["package_id"]}"',
        ),
        (
            "flutter/macos/Runner/Configs/AppInfo.xcconfig",
            "PRODUCT_BUNDLE_IDENTIFIER = com.carriez.flutterHbb",
            f'PRODUCT_BUNDLE_IDENTIFIER = {profile["package_id"]}',
        ),
        (
            "flutter/windows/runner/Runner.rc",
            'VALUE "ProductName", "RustDesk" "\\0"',
            f'VALUE "ProductName", "{profile["product_name"]}" "\\0"',
        ),
        ("res/rustdesk.desktop", "Name=RustDesk", f'Name={profile["product_name"]}'),
        ("res/rustdesk-link.desktop", "Name=RustDesk", f'Name={profile["product_name"]}'),
        (
            "res/rustdesk.desktop",
            "Icon=rustdesk",
            "Icon=/usr/share/icons/hicolor/256x256/apps/rustdesk.png",
        ),
        (
            "res/rustdesk-link.desktop",
            "Icon=rustdesk",
            "Icon=/usr/share/icons/hicolor/256x256/apps/rustdesk.png",
        ),
    )
    for relative, old, new in replacements:
        path = root / relative
        if not path.is_file():
            continue
        original = path.read_text(encoding="utf-8")
        updated = replace_strict(original, old, new, path)
        if updated != original:
            branding_updates.append((path, updated, original))
    lib = inject_once(lib, LIB_ANCHOR, "mod build_profile;", f"mod build_profile;\n{LIB_ANCHOR}")
    common = inject_once(
        common,
        COMMON_ANCHOR,
        "crate::build_profile::apply();",
        f"{COMMON_ANCHOR}\n    crate::build_profile::apply();",
    )

    # Write only after all anchors have been validated so a partial patch is impossible.
    (root / "src" / "build_profile.rs").write_text(render_profile(profile), encoding="utf-8")
    lib_path.write_text(lib, encoding="utf-8")
    common_path.write_text(common, encoding="utf-8")
    for path, updated, _original in branding_updates:
        path.write_text(updated, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True, type=Path, help="RustDesk source root")
    parser.add_argument("--profile", required=True, type=Path, help="JSON build profile")
    args = parser.parse_args()
    try:
        profile = json.loads(args.profile.read_text(encoding="utf-8"))
        if not isinstance(profile, dict):
            raise ProfileError("profile root must be a JSON object")
        configure_source(profile, args.root.resolve())
    except (OSError, json.JSONDecodeError, ProfileError, PatchError) as exc:
        parser.exit(2, f"error: {exc}\n")
    print(f"applied {profile['product_name']} profile to {args.root.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
